"""
Conversation eval cases for the virtual waiter — the questions guests actually ask.

Each case is one or more guest turns against the live tenant menu. Checks run on the
LAST turn (reply + UI meta) and on the simulated cart after every turn.

  cart        starting cart {item name: qty}
  intent      acceptable final intents
  cart_after  exact expected cart {item name: qty} (None = don't check)
  cart_same   cart must not change during the case
  confirmed   True/False: whether the order must (not) have been confirmed
  say_any     reply must contain at least one of these (case-insensitive)
  say_not     reply must contain none of these
  lang        expected reply script: "en" (latin) or "bn" (bengali)
  judge       what a great waiter does here (LLM-judge rubric)
"""
